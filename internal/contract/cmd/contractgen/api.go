const (
	apiDir        = "internal/contract/api"
	modelsImport  = "github.com/SDK-E/agentsone/internal/contract/api"
	coreImport    = "github.com/SDK-E/agentsone/internal/core"
	eventStream   = "text/event-stream"
	generatedNote = "// Code generated by contractgen. DO NOT EDIT.\n\n"
)

var httpMethods = []string{"get", "put", "post", "delete", "options", "head", "patch", "trace"}

type spec struct {
	raw   []byte
	doc   map[string]any
	paths map[string]map[string]any
}

type operation struct {
	Method      string
	Path        string
	OperationID string
	Tag         string
	Stream      bool
}

type group struct {
	Tag     string
	Package string
	Ops     []operation
}

func loadSpec(path string) (spec, error) {
	raw, err := os.ReadFile(path) // #nosec G304 -- the bundled contract inside the repository
	if err != nil {
		return spec{}, fmt.Errorf("read bundled spec (run the redocly bundle first): %w", err)
	}
	s := spec{raw: raw}
	if err := json.Unmarshal(raw, &s.doc); err != nil {
		return spec{}, fmt.Errorf("parse bundled spec: %w", err)
	}
	if err := json.Unmarshal(raw, &struct {
		Paths *map[string]map[string]any `json:"paths"`
	}{&s.paths}); err != nil {
		return spec{}, fmt.Errorf("parse paths: %w", err)
	}
	return s, nil
}

func (s spec) operations() ([]operation, error) {
	var ops []operation
	for path, item := range s.paths {
		for _, m := range httpMethods {
			raw, ok := item[m].(map[string]any)
			if !ok {
				continue
			}
			op, err := newOperation(m, path, raw)
			if err != nil {
				return nil, err
			}
			ops = append(ops, op)
		}
	}
	sort.Slice(ops, func(i, j int) bool {
		if ops[i].Path != ops[j].Path {
			return ops[i].Path < ops[j].Path
		}
		return ops[i].Method < ops[j].Method
	})
	return ops, nil
}

func newOperation(method, path string, raw map[string]any) (operation, error) {
	id, _ := raw["operationId"].(string)
	if id == "" {
		return operation{}, fmt.Errorf("%s %s has no operationId", method, path)
	}
	tags, _ := raw["tags"].([]any)
	if len(tags) == 0 {
		return operation{}, fmt.Errorf("operation %s has no tag; the first tag picks its group", id)
	}
	tag, _ := tags[0].(string)
	return operation{
		Method:      strings.ToUpper(method),
		Path:        path,
		OperationID: id,
		Tag:         tag,
		Stream:      streams(raw),
	}, nil
}

func streams(op map[string]any) bool {
	responses, _ := op["responses"].(map[string]any)
	for code, r := range responses {
		if !strings.HasPrefix(code, "2") {
			continue
		}
		content, _ := r.(map[string]any)["content"].(map[string]any)
		if _, ok := content[eventStream]; ok {
			return true
		}
	}
	return false
}

var nonAlnum = regexp.MustCompile(`[^a-z0-9]+`)

func packageFor(tag string) string {
	return nonAlnum.ReplaceAllString(strings.ToLower(tag), "") + "api"
}

func groupsOf(ops []operation) ([]group, error) {
	byTag := map[string]*group{}
	pkgTag := map[string]string{}
	for _, op := range ops {
		g, ok := byTag[op.Tag]
		if !ok {
			pkg := packageFor(op.Tag)
			if other, clash := pkgTag[pkg]; clash {
				return nil, fmt.Errorf("tags %q and %q map to the same package %s", other, op.Tag, pkg)
			}
			pkgTag[pkg] = op.Tag
			g = &group{Tag: op.Tag, Package: pkg}
			byTag[op.Tag] = g
		}
		g.Ops = append(g.Ops, op)
	}
	groups := make([]group, 0, len(byTag))
	for _, g := range byTag {
		groups = append(groups, *g)
	}
	sort.Slice(groups, func(i, j int) bool { return groups[i].Tag < groups[j].Tag })
	return groups, nil
}

func generateAPI(r repo, s spec) error {
	ops, err := s.operations()
	if err != nil {
		return err
	}
	groups, err := groupsOf(ops)
	if err != nil {
		return err
	}
	if err := r.removeGenerated(apiDir); err != nil {
		return err
	}
	if err := r.write(apiDir+"/openapi.json", s.raw); err != nil {
		return err
	}
	tmp, err := os.MkdirTemp("", "contractgen-")
	if err != nil {
		return fmt.Errorf("temp dir: %w", err)
	}
	defer func() { _ = os.RemoveAll(tmp) }()

	if err := generateModels(r, tmp); err != nil {
		return err
	}
	if err := writeRoutes(r, ops); err != nil {
		return err
	}
	for _, g := range groups {
		if err := generateGroup(r, s, g, tmp); err != nil {
			return fmt.Errorf("group %s: %w", g.Tag, err)
		}
	}
	return nil
}

func generateModels(r repo, tmp string) error {
	cfg := "package: api\n" +
		"generate:\n  models: true\n" +
		"compatibility:\n  always-prefix-enum-values: true\n" +
		"output-options:\n  skip-prune: true\n"
	cfgPath := filepath.Join(tmp, "models.yaml")
	if err := os.WriteFile(cfgPath, []byte(cfg), 0o600); err != nil {
		return fmt.Errorf("write models config: %w", err)
	}
	out, err := r.goTool("oapi-codegen", "-config", cfgPath, r.path("contract/dist/openapi.json"))
	if err != nil {
		return err
	}
	return r.writeGo(apiDir+"/models.gen.go", out)
}

func generateGroup(r repo, s spec, g group, tmp string) error {
	specPath := filepath.Join(tmp, g.Package+".json")
	if err := os.WriteFile(specPath, s.only(g), 0o600); err != nil {
		return fmt.Errorf("write group spec: %w", err)
	}
	cfg := "package: " + g.Package + "\n" +
		"generate:\n  std-http-server: true\n  strict-server: true\n" +
		"compatibility:\n  always-prefix-enum-values: true\n" +
		"additional-imports:\n  - package: " + modelsImport + "\n    alias: .\n"
	cfgPath := filepath.Join(tmp, g.Package+".yaml")
	if err := os.WriteFile(cfgPath, []byte(cfg), 0o600); err != nil {
		return fmt.Errorf("write group config: %w", err)
	}
	server, err := r.goTool("oapi-codegen", "-config", cfgPath, specPath)
	if err != nil {
		return err
	}
	dir := apiDir + "/" + g.Package
	if err := r.writeGo(dir+"/server.gen.go", server); err != nil {
		return err
	}
	methods, err := strictMethods(server)
	if err != nil {
		return err
	}
	src, err := render(groupTemplate, map[string]any{"Group": g, "Methods": methods, "Core": coreImport})
	if err != nil {
		return err
	}
	return r.writeGo(dir+"/group.gen.go", src)
}

// only returns the spec with just the group's operations, so each operation
// is generated in exactly one package.
func (s spec) only(g group) []byte {
	owned := map[string]bool{}
	for _, op := range g.Ops {
		owned[op.Method+" "+op.Path] = true
	}
	paths := map[string]any{}
	for path, item := range s.paths {
		kept := map[string]any{}
		for k, v := range item {
			isMethod := false
			for _, m := range httpMethods {
				if k == m {
					isMethod = true
				}
			}
			if !isMethod || owned[strings.ToUpper(k)+" "+path] {
				kept[k] = v
			}
		}
		if len(kept) > len(nonMethodKeys(item)) {
			paths[path] = kept
		}
	}
	doc := map[string]any{}
	for k, v := range s.doc {
		doc[k] = v
	}
	doc["paths"] = paths
	b, _ := json.Marshal(doc) // re-marshalling decoded JSON cannot fail
	return b
}

func nonMethodKeys(item map[string]any) []string {
	var keys []string
	for k := range item {
		method := false
		for _, m := range httpMethods {
			if k == m {
				method = true
			}
		}
		if !method {
			keys = append(keys, k)
		}
	}
	return keys
}

func writeRoutes(r repo, ops []operation) error {
	src, err := render(routesTemplate, ops)
	if err != nil {
		return err
	}
	return r.writeGo(apiDir+"/routes.gen.go", src)
}

func render(t *template.Template, data any) ([]byte, error) {
	var b bytes.Buffer
	if err := t.Execute(&b, data); err != nil {
		return nil, fmt.Errorf("render %s: %w", t.Name(), err)
	}
	return b.Bytes(), nil
}

var routesTemplate = template.Must(template.New("routes").Parse(generatedNote + `package api

// Routes lists every operation in the contract, sorted by path then method.
var Routes = []Route{
{{- range .}}
	{Method: "{{.Method}}", Path: "{{.Path}}", OperationID: "{{.OperationID}}", Tag: "{{.Tag}}", Stream: {{.Stream}}},
{{- end}}
}
`))

var groupTemplate = template.Must(template.New("group").Parse(generatedNote + `package {{.Group.Package}}

import (
	"context"
	"net/http"

	"{{.Core}}"
)

// Tag is the OpenAPI tag this package serves.
const Tag = "{{.Group.Tag}}"

// Group mounts impl as the "{{.Group.Tag}}" group.
func Group(impl StrictServerInterface, middlewares ...StrictMiddlewareFunc) core.APIGroup {
	return core.APIGroup{
		Tag: Tag,
		Register: func(mux *http.ServeMux, o core.APIOptions) {
			h := NewStrictHandlerWithOptions(impl, middlewares, StrictHTTPServerOptions{
				RequestErrorHandlerFunc:  o.RequestError,
				ResponseErrorHandlerFunc: o.ResponseError,
			})
			HandlerWithOptions(h, StdHTTPServerOptions{BaseRouter: mux, ErrorHandlerFunc: o.RequestError})
		},
	}
}

// Unimplemented answers core.ErrNotImplemented (501) for every operation.
// Embed it and override operations one at a time.
type Unimplemented struct{}

var _ StrictServerInterface = Unimplemented{}
{{range .Methods}}
// {{.Name}} is not implemented yet.
func (Unimplemented) {{.Name}}(context.Context, {{.Request}}) ({{.Response}}, error) {
	return nil, core.ErrNotImplemented
}
{{end}}`))
