// Generate TypeScript types from the Agents One contract.
//
//   contract/dist/openapi.json          -> src/generated/openapi.ts
//   contract/schemas/**/*.schema.json   -> src/generated/schemas/<same path>.ts
//
// Output is deterministic: files are processed in sorted order, nothing depends on the clock,
// and everything is formatted with the repository Prettier config. Stale files are removed.
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { compile } from "json-schema-to-typescript";
import openapiTS, { astToString } from "openapi-typescript";
import * as prettier from "prettier";

const here = path.dirname(fileURLToPath(import.meta.url));
const pkgDir = path.resolve(here, "..");
const repoDir = path.resolve(pkgDir, "../..");
const specFile = path.join(repoDir, "contract/dist/openapi.json");
const schemaDir = path.join(repoDir, "contract/schemas");
const outDir = path.join(pkgDir, "src/generated");

const SPDX = "// SPDX-License-Identifier: MIT";

/** Header for every generated file. */
function banner(source) {
  return `${SPDX}\n// Code generated by @agentsone/contract scripts/gen.mjs from ${source}. DO NOT EDIT.\n\n`;
}

/** Format TypeScript source with the repository Prettier config. */
async function format(file, source) {
  const config = (await prettier.resolveConfig(file)) ?? {};
  return prettier.format(source, { ...config, filepath: file });
}

async function emit(file, source) {
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, await format(file, source));
}

/** List every *.schema.json under dir, sorted, as paths relative to dir with "/" separators. */
async function listSchemas(dir) {
  let entries;
  try {
    entries = await readdir(dir, { recursive: true, withFileTypes: true });
  } catch (err) {
    if (err.code === "ENOENT") return [];
    throw err;
  }
  return entries
    .filter((e) => e.isFile() && e.name.endsWith(".schema.json"))
    .map((e) => path.relative(dir, path.join(e.parentPath, e.name)).split(path.sep).join("/"))
    .sort();
}

/** "runner/wake.schema.json" -> "RunnerWakeSchema". */
function namespaceName(rel) {
  const words = rel
    .replace(/\.schema\.json$/, "")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean);
  return `${words.map((w) => w[0].toUpperCase() + w.slice(1)).join("")}Schema`;
}

/**
 * Remove `$defs` from component schemas. The bundle keeps the `$defs` of JSON Schemas it
 * inlined from contract/schemas, and openapi-typescript would render each as a required
 * `$defs` member of the object type. Bundling already lifts every referenced definition into
 * its own component, so these copies are unreachable; fail loudly if that ever changes.
 */
function dropDefs(spec) {
  const text = JSON.stringify(spec);
  if (/"\$ref":"#\/components\/schemas\/[^"]*\/\$defs\//.test(text)) {
    throw new Error("contract/dist/openapi.json has a $ref into a $defs block; cannot drop $defs");
  }
  for (const schema of Object.values(spec.components?.schemas ?? {})) {
    if (schema && typeof schema === "object") delete schema.$defs;
  }
  return spec;
}

async function genOpenAPI() {
  const spec = dropDefs(JSON.parse(await readFile(specFile, "utf8")));
  const ast = await openapiTS(spec, { alphabetize: false });
  const file = path.join(outDir, "openapi.ts");
  await emit(file, banner("contract/dist/openapi.json") + astToString(ast));
}

async function genSchemas() {
  const rels = await listSchemas(schemaDir);

  // Map every schema $id (and the folder it names) to the local file, so that $ref values
  // written as absolute URLs resolve from disk and never reach the network.
  const byId = new Map();
  for (const rel of rels) {
    const abs = path.join(schemaDir, rel);
    const schema = JSON.parse(await readFile(abs, "utf8"));
    if (typeof schema.$id === "string") byId.set(schema.$id.split("#")[0], abs);
  }
  const localFor = (url) => {
    const bare = url.split("#")[0];
    if (byId.has(bare)) return byId.get(bare);
    for (const [id, abs] of byId) {
      const base = id.slice(0, id.lastIndexOf("/") + 1);
      if (bare.startsWith(base)) return path.join(path.dirname(abs), bare.slice(base.length));
    }
    return undefined;
  };
  const resolver = {
    order: 1,
    canRead: (file) => localFor(file.url) !== undefined,
    read: (file) => readFile(localFor(file.url), "utf8"),
  };

  const index = [];
  for (const rel of rels) {
    const abs = path.join(schemaDir, rel);
    const schema = JSON.parse(await readFile(abs, "utf8"));
    const name = namespaceName(rel);
    const ts = await compile(schema, name, {
      bannerComment: "",
      cwd: path.dirname(abs),
      declareExternallyReferenced: true,
      unreachableDefinitions: true,
      additionalProperties: false,
      format: false,
      $refOptions: { resolve: { http: false, agentsone: resolver } },
    });
    const outRel = rel.replace(/\.schema\.json$/, ".ts");
    await emit(path.join(outDir, "schemas", outRel), banner(`contract/schemas/${rel}`) + ts);
    index.push(`export type * as ${name} from "./${outRel.replace(/\.ts$/, ".js")}";`);
  }

  await emit(
    path.join(outDir, "schemas/index.ts"),
    banner("contract/schemas") + (index.length ? index.join("\n") + "\n" : "export {};\n"),
  );
}

await rm(outDir, { recursive: true, force: true });
await genOpenAPI();
await genSchemas();
